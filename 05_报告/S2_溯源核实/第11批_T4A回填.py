def find_lock(ent):
    if ent == "病毒性肝炎":
        return ("", "10.3760/cma.j.cn501113-20240901-00461", "中华肝脏病杂志 2024,32(12):1123-1133",
                "https://doi.org/10.3760/cma.j.cn501113-20240901-00461",
                "张济深/胡小雄等（宜春市人民医院），TMF vs TAF对机体脂质代谢的影响比较（中华肝脏病杂志「病毒性肝炎」栏目）")
    for sub, pmid, doi, j, link, note in LOCK:
        if sub in ent:
            return (pmid, doi, j, link, note)
    return None


def find_excl(ent):
    for sub, reason in EXCL:
        if sub in ent:
            return reason
    return None


def main():
    rows = list(csv.reader(io.open(LEDGER, encoding="utf-8-sig")))
    header, data = rows[0], rows[1:]
    n_lock = n_excl = 0
    unhandled = []
    for r in data:
        if not (r[0] == "T4A_初治" and r[7] == "待核实"):
            continue
        ent = r[1]
        if r[5] == "肝病知识":
            r[7] = "已剔除"
            r[12] = "非期刊来源：患者科普（肝病知识栏目，恩替卡韦/替诺福韦用药问答）"
            n_excl += 1
            continue
        lk = find_lock(ent)
        if lk:
            r[7] = "已锁定"
            r[8], r[9], r[10], r[11] = lk[0], lk[1], lk[2], lk[3]
            r[12] = lk[4]
            n_lock += 1
            continue
        ex = find_excl(ent)
        if ex:
            r[7] = "已剔除"
            r[12] = ex
            n_excl += 1
            continue
        unhandled.append(ent)
    if unhandled:
        print("!! 未处理条目（未写回）:")
        for u in unhandled:
            print("   -", u)
        raise SystemExit("存在未处理条目，已中止写回，请补充规则")
    with io.open(LEDGER, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(data)
    print("第11批回填完成：T4A 已锁定 {} 条 / 已剔除 {} 条".format(n_lock, n_excl))


if __name__ == "__main__":
    main()
