def main():
    rows = list(csv.reader(io.open(LEDGER, encoding="utf-8-sig")))
    header, data = rows[0], rows[1:]
    # 列索引（与 LEDGER_HEADER 一致）
    # 0专题 1实体名 2出现次数 3最高优先级 4年份 5来源媒体 6代表候选标题
    # 7溯源状态 8PMID 9DOI 10期刊年卷期 11官方链接 12剔除原因/备注
    update_map = {u[0]: u for u in UPDATES}
    matched = set()
    for r in data:
        ent = r[1]
        if ent in update_map:
            u = update_map[ent]
            # 有 PMID/DOI/期刊/链接任一引用信息 => 已锁定（备注仅作补充说明）
            # 引用信息全空且备注非空 => 已剔除（备注写入剔除原因）
            r[7] = "已锁定" if (u[1] or u[2] or u[3] or u[4]) else "已剔除"
            r[8] = u[1]
            r[9] = u[2]
            r[10] = u[3]
            r[11] = u[4]
            if u[5]:
                r[12] = u[5]
            matched.add(ent)
    missing = set(update_map) - matched
    # 追加新行（幂等：实体已存在则只补状态，不重复追加）
    # APPEND 定义允许 12 列（缺溯源状态列），此处自动补全为 13 列
    exist_names = {r[1] for r in data}
    for a in APPEND:
        row = list(a)
        while len(row) < 13:
            row.append("")
        row[7] = "已锁定"  # APPEND 均为已锁定文献
        if row[1] in exist_names:
            # 更新已有行（补全状态与引用字段）
            for i, r in enumerate(data):
                if r[1] == row[1]:
                    for c in range(13):
                        if row[c]:
                            data[i][c] = row[c]
        else:
            data.append(row)
            exist_names.add(row[1])
    with io.open(LEDGER, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(data)
    print("已回填 {} 条已锁定文献".format(len(matched)))
    if missing:
        print("!! 未匹配到台账实体的条目：")
        for m in missing:
            print("   -", m)
    print("APPEND 处理 {} 条：{}".format(len(APPEND), "、".join(a[1] for a in APPEND)))
    print("台账现有总行数：{}（含表头）".format(len(data) + 1))

if __name__ == "__main__":
    main()
